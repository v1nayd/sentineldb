import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { minutes, q, ReplayScript } from "./replay";

/**
 * The Milestone 1 spike seed (12 incidents), now replayed through the lifecycle instead of inserted in final states.
 * Same users, assets, IOCs, titles, narratives, final statuses, assignees, created_at and resolved_at as the M1 file,
 * so `npm run spike` keeps exercising the same texts. Data: spike-data.json (extracted verbatim from the M1 SQL).
 */
interface SpikeData {
  users: Array<{ id: number; name: string; email: string; role: string; createdAt: string }>;
  assets: Array<{ id: number; name: string; type: string; ip: string; criticality: number; department: string }>;
  iocs: Array<{ id: number; type: string; value: string; firstSeen: string; threat: string }>;
  incidents: Array<{ id: number; title: string; narrative: string; severity: string; finalStatus: string; reportedBy: number; assignedTo: number | null; createdAt: string; resolvedAt: string | null }>;
  iocLinks: Array<[number, number, string]>;
  assetLinks: Array<[number, number, string]>;
}

const ADMIN = 2;
const utc = (s: string) => new Date(`${s.replace(" ", "T")}Z`);

export function buildSpikeSeed(): string {
  const data = JSON.parse(readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), "spike-data.json"), "utf8")) as SpikeData;
  const s = new ReplayScript([
    "SYNTHETIC DATA. GENERATED by scripts/generate-seed.ts from scripts/seed/spike-data.json; do not edit by hand.",
    "Milestone 1 vertical-slice seed (12 incidents), replayed through the real lifecycle (docs/DECISIONS.md ADR-2).",
    "Identifiers are documentation-reserved only: RFC 5737 IPs, .example / .invalid domains, made-up hashes.",
    "password_hash is deliberately NOT a valid hash, so these accounts cannot log in.",
    "Load into an EMPTY, freshly migrated database: npm run db:reset && npm run db:seed -- spike",
  ]);

  s.raw("INSERT INTO Users (user_id, name, email, password_hash, role, created_at) VALUES");
  s.raw(data.users.map((u) => `  (${u.id}, ${q(u.name)}, ${q(u.email)}, '!SEED-NO-LOGIN!', ${q(u.role)}, '${u.createdAt}')`).join(",\n") + ";");
  s.raw("INSERT INTO Assets (asset_id, asset_name, asset_type, ip_address, criticality_level, owner_department) VALUES");
  s.raw(data.assets.map((a) => `  (${a.id}, ${q(a.name)}, ${q(a.type)}, ${q(a.ip)}, ${a.criticality}, ${q(a.department)})`).join(",\n") + ";");
  s.raw("INSERT INTO IOCs (ioc_id, ioc_type, ioc_value, first_seen, threat_level) VALUES");
  s.raw(data.iocs.map((c) => `  (${c.id}, ${q(c.type)}, ${q(c.value)}, '${c.firstSeen}', ${q(c.threat)})`).join(",\n") + ";");

  for (const inc of data.incidents) {
    s.comment(`incident ${inc.id}: ${inc.title} -> ${inc.finalStatus}`);
    const t0 = utc(inc.createdAt);
    s.createIncident({ id: inc.id, title: inc.title, narrative: inc.narrative, severity: inc.severity, reportedBy: inc.reportedBy, at: t0 });
    const iocs = data.iocLinks.filter(([i]) => i === inc.id);
    for (const [, ioc, notes] of iocs) s.linkIoc(inc.reportedBy, minutes(t0, 5), inc.id, ioc, notes);
    for (const [, asset, impact] of data.assetLinks.filter(([i]) => i === inc.id)) s.linkAsset(inc.reportedBy, minutes(t0, 5), inc.id, asset, impact);
    if (inc.assignedTo === null) continue;

    s.reassign(ADMIN, minutes(t0, 15), inc.id, inc.assignedTo, "Triage");
    if (inc.finalStatus === "open") continue;
    s.transition(inc.assignedTo, minutes(t0, 30), inc.id, "investigating");
    if (inc.finalStatus === "investigating") continue;
    if (inc.finalStatus === "contained") { s.transition(inc.assignedTo, minutes(t0, 180), inc.id, "contained"); continue; }

    const resolved = utc(inc.resolvedAt!);
    for (const [, ioc] of iocs) s.reviewIoc(inc.assignedTo, minutes(resolved, -30), inc.id, ioc, "confirmed");
    s.transition(inc.assignedTo, resolved, inc.id, "resolved");
    if (inc.finalStatus === "closed") s.close(ADMIN, minutes(resolved, 120), inc.id, "Reviewed and closed");
  }
  return s.toString();
}
