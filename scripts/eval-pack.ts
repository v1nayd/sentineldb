/**
 * Generates eval/writer-pack.md: everything a query writer may see (eval/README.md, "What the writer may see").
 * Family names, campaign and chain labels, their IOCs with a source incident, their assets. Deliberately NO titles and
 * NO narratives: both come from the seed templates, and reading them would leak template wording into the queries.
 *   npm run eval:pack       (demo seed loaded; read-only, runtime account)
 */
import { readFile, writeFile } from "node:fs/promises";
import type { RowDataPacket } from "mysql2/promise";
import { loadEnv } from "../src/lib/env";
await loadEnv();
const { appPool, closeAppPool, placeholders } = await import("../src/lib/db");

const labels = JSON.parse(await readFile("db/seed/demo_labels.json", "utf8")) as { incidents: Array<{ incident_id: number; family: string; campaign: string | null; chain: string | null }> };
const pool = appPool();
try {
  const [active] = await pool.query<RowDataPacket[]>("SELECT incident_id FROM Incidents WHERE archived_at IS NULL");
  const live = new Set(active.map((r) => Number(r.incident_id)));
  if (labels.incidents.filter((l) => live.has(l.incident_id)).length !== live.size || live.size === 0) throw new Error("the loaded data is not the labelled demo seed: npm run db:reset && npm run db:grants && npm run db:seed -- demo");
  const families = new Map<string, number>();
  for (const l of labels.incidents) if (live.has(l.incident_id)) families.set(l.family, (families.get(l.family) ?? 0) + 1);
  const md = [
    "# Query writer's pack (generated by `npm run eval:pack`)", "",
    "Read `eval/README.md` first. This file is all you need: do not open the UI, the seed files or the database.", "",
    "## Families (`family` field; number of active incidents)", "",
    ...[...families].sort().map(([f, n]) => `- \`${f}\` (${n})`), "",
    "## Campaigns and chains (`campaign` / `chain` field)", "",
    "Each IOC is shown with the incident it comes from: copy that number into `source_incident`. At most 3 IOCs per query.", "",
  ];
  const [assets] = await pool.query<RowDataPacket[]>("SELECT asset_name FROM Assets ORDER BY asset_name");
  for (const key of ["campaign", "chain"] as const) {
    const groups = [...new Set(labels.incidents.map((l) => l[key]).filter((v): v is string => v !== null))].sort();
    for (const g of groups) {
      const ids = labels.incidents.filter((l) => l[key] === g && live.has(l.incident_id)).map((l) => l.incident_id);
      if (ids.length === 0) continue;
      const [iocs] = await pool.query<RowDataPacket[]>(
        `SELECT MIN(l.incident_id) AS source, c.ioc_type, c.ioc_value, COUNT(*) AS n FROM Incident_IOC l JOIN IOCs c ON c.ioc_id = l.ioc_id
          WHERE l.incident_id IN (${placeholders(ids.length)}) AND l.review_status <> 'dismissed' GROUP BY c.ioc_type, c.ioc_value ORDER BY n DESC, c.ioc_value`, ids);
      const [used] = await pool.query<RowDataPacket[]>(
        `SELECT DISTINCT a.asset_name FROM Incident_Asset l JOIN Assets a ON a.asset_id = l.asset_id WHERE l.incident_id IN (${placeholders(ids.length)}) ORDER BY a.asset_name`, ids);
      md.push(`### \`${key}\`: \`${g}\` (${ids.length} active incidents)`, "", `Assets: ${used.map((u) => `\`${u.asset_name}\``).join(", ") || "none"}`, "");
      for (const i of iocs) md.push(`- ${i.ioc_type} \`${i.ioc_value}\` — source_incident ${i.source}, in ${i.n} of these incidents`);
      md.push("");
    }
  }
  md.push("## All asset names (`asset_names` field; at most 2 per query)", "", assets.map((a) => `\`${a.asset_name}\``).join(", "), "");
  await writeFile("eval/writer-pack.md", md.join("\n"));
  console.log(`written: eval/writer-pack.md (${families.size} families)`);
} finally {
  await closeAppPool();
}
